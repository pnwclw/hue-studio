"""Build the bundled Hue light icons from elax46/custom-brand-icons (MIT).

Writes `src/hue-icons-data.ts`: the icons `src/model.ts` names as `hue-studio:<name>`
(the Hue app's light shapes), each as its SVG view box and path. The frontend registers
them as the `hue-studio:` icon set, so `<ha-icon icon="hue-studio:bulb-candle">` works
without the HACS plugin installed.

Usage: uv run python scripts/build_hue_icons.py
Downloads the pinned release's `custom-brand-icons.js` and reads it as text only (the
`"name":[x,y,width,height,"path"]` entries); nothing from it is run.
"""

from __future__ import annotations

import json
from pathlib import Path
import re
import sys
import urllib.request

REPO = "elax46/custom-brand-icons"
VERSION = "2026.10.1"
URL = f"https://github.com/{REPO}/releases/download/{VERSION}/custom-brand-icons.js"

ROOT = Path(__file__).resolve().parent.parent
MODEL = ROOT / "src" / "model.ts"
OUT = ROOT / "src" / "hue-icons-data.ts"

ENTRY = re.compile(r'^\s*"([^"]+)":(\[.*\]),?\s*$', re.MULTILINE)
WANTED = re.compile(r'"hue-studio:([a-z0-9-]+)"')


def main() -> None:
    """Download the icon set, keep the icons the model uses, write the TS module."""
    wanted = sorted(set(WANTED.findall(MODEL.read_text())))
    with urllib.request.urlopen(URL, timeout=60) as response:
        source = response.read().decode()
    icons: dict[str, list] = {}
    for name, data in ENTRY.findall(source):
        if name in wanted:
            icons[name] = json.loads(data)
    missing = [name for name in wanted if name not in icons]
    if missing:
        sys.exit(f"not in {REPO} {VERSION}: {', '.join(missing)}")

    lines = [
        f"// Generated by scripts/build_hue_icons.py from {REPO} {VERSION}"
        " (MIT, see NOTICE).",
        "// Do not edit: rerun the script after changing the icons named in model.ts.",
        "",
        "/** Icon name -> [SVG view box, path]. */",
        "export const HUE_ICONS: Record<string, [string, string]> = {",
    ]
    for name in wanted:
        x, y, width, height, path = icons[name][:5]
        box = json.dumps(f"{x} {y} {width} {height}")
        lines.append(f"  {json.dumps(name)}: [{box}, {json.dumps(path)}],")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(wanted)} icons -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
